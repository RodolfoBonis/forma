/// Spacing tokens for the Forma Design System.
///
/// Provides a consistent spacing scale used across all Forma components
/// for margins, padding, and gaps.
abstract class FormaSpacing {
  /// 4px — extra-small spacing for tight inner padding.
  static const double xs = 4;

  /// 8px — small spacing for compact layouts.
  static const double sm = 8;

  /// 12px — medium spacing between related elements.
  static const double md = 12;

  /// 16px — base spacing unit; default padding / gap.
  static const double base = 16;

  /// 20px — large spacing for section separation.
  static const double lg = 20;

  /// 24px — extra-large spacing.
  static const double xl = 24;

  /// 32px — double-extra-large spacing for major sections.
  static const double xxl = 32;

  /// 40px — triple-extra-large spacing.
  static const double xxxl = 40;

  /// 48px — huge spacing for prominent visual breaks.
  static const double huge = 48;
}
