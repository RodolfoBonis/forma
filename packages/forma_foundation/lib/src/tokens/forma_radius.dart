/// Border-radius tokens for the Forma Design System.
///
/// Provides a consistent rounding scale used across all Forma components.
abstract class FormaRadius {
  /// 4px — subtle rounding for inline elements.
  static const double subtle = 4;

  /// 8px — standard input field rounding.
  static const double input = 8;

  /// 12px — small card / container rounding.
  static const double small = 12;

  /// 16px — default card rounding.
  static const double card = 16;

  /// 18px — button rounding.
  static const double button = 18;

  /// 20px — large card rounding.
  static const double cardLg = 20;

  /// 22px — large generic rounding.
  static const double large = 22;

  /// 24px — chip rounding.
  static const double chip = 24;

  /// 28px — bottom-sheet rounding.
  static const double sheet = 28;

  /// 40px - extra large generic rounding
  static const double xlarge = 40;

  /// 54px — app icon rounding.
  static const double appIcon = 54;
}
